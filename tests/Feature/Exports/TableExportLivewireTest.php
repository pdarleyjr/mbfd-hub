    public function test_user_without_view_any_cannot_see_or_run_the_export(): void
    {
        $this->location('North Cage', 'A', '1');
        $page = Livewire::test(ListInventoryLocations::class)->call('loadTable')->assertTableActionVisible('export');

        // Permission is revoked after the page was loaded: the server must re-check on execution.
        $limited = $this->userWith('admin.access');
        $this->actingAs($limited);
        Auth::guard('web')->setUser($limited);

        self::assertFalse(InventoryLocationResource::canExportTable());
        $page->assertTableActionHidden('export');
        // Bypass the test helper's visibility guard and drive the raw Livewire calls a hostile client could send.
        $page->call('mountTableAction', 'export')
            ->set('mountedTableActionsData.0.format', 'xlsx')
            ->set('mountedTableActionsData.0.scope', 'all')
            ->call('callMountedTableAction');
        self::assertArrayNotHasKey('download', $page->effects);
        self::assertSame(0, SecurityActionEvent::query()->where('action', 'table_export')->where('result', 'allowed')->count());
    }

    public function test_service_refuses_and_audits_a_user_without_view_any(): void
    {
        $page = Livewire::test(ListInventoryLocations::class)->call('loadTable');
        $limited = $this->userWith('admin.access');

        try {
            app(\App\Services\Exports\TableExportService::class)->download($limited, $page->instance(), InventoryLocationResource::class, 'xlsx', 'all');
            self::fail('A user without viewAny must not be able to export.');
        } catch (\Symfony\Component\HttpKernel\Exception\HttpException $exception) {
            self::assertSame(403, $exception->getStatusCode());
        }

        $event = SecurityActionEvent::query()->where('action', 'table_export')->sole();
        self::assertSame('denied', $event->result);
        self::assertSame($limited->getKey(), $event->actor_user_id);
    }

    public function test_each_export_is_audited_with_scope_format_and_row_count(): void
    {
        $this->location('North Cage', 'A', '1');
        $this->location('South Cage', 'B', '2');

        Livewire::test(ListInventoryLocations::class)->call('loadTable')
            ->callTableAction('export', data: ['format' => 'xlsx', 'scope' => 'all']);

        $event = SecurityActionEvent::query()->where('action', 'table_export')->sole();
        self::assertSame('allowed', $event->result);
        self::assertSame($this->admin->getKey(), $event->actor_user_id);
        self::assertSame(InventoryLocationResource::class, $event->metadata['resource']);
        self::assertSame('all', $event->metadata['scope']);
        self::assertSame('xlsx', $event->metadata['format']);
        self::assertSame(2, $event->metadata['row_count']);
    }

    public function test_single_gas_meter_export_has_typed_dates_numbers_and_relationship_text(): void
    {
        $apparatus = Apparatus::query()->create([
            'unit_id' => 'E1', 'name' => 'Engine 1', 'type' => 'Engine', 'vehicle_number' => '1001', 'designation' => 'E1',
            'slug' => 'engine-1', 'make' => 'Pierce', 'model' => 'Enforcer', 'year' => 2021, 'status' => 'In Service',
            'current_engine_hours' => 10, 'current_miles' => 100,
        ]);
        SingleGasMeter::query()->create(['apparatus_id' => $apparatus->id, 'serial_number' => '00A12', 'activation_date' => '2026-03-05']);

        $component = Livewire::test(ListSingleGasMeters::class)->call('loadTable')
            ->callTableAction('export', data: ['format' => 'xlsx', 'scope' => 'filtered'])
            ->assertHasNoTableActionErrors();
        $sheet = $this->workbook($component)->getSheet(0);

        self::assertSame(['Apparatus', 'Serial Number', 'Activation Date', 'Expiration Date', 'Status', 'Days Until Expiration'], array_slice($this->dataRows($this->workbook($component))[0], 0, 6));
        self::assertSame('E1', $sheet->getCell('A2')->getValue());
        self::assertSame(DataType::TYPE_STRING, $sheet->getCell('B2')->getDataType());
        self::assertSame('00A12', $sheet->getCell('B2')->getValue());
        self::assertSame(DataType::TYPE_NUMERIC, $sheet->getCell('C2')->getDataType());
        self::assertSame('2026-03-05', Date::excelToDateTimeObject($sheet->getCell('C2')->getValue())->format('Y-m-d'));
        self::assertSame('2028-03-05', Date::excelToDateTimeObject($sheet->getCell('D2')->getValue())->format('Y-m-d'));
        self::assertSame('Valid', $sheet->getCell('E2')->getValue());
        self::assertSame(DataType::TYPE_NUMERIC, $sheet->getCell('F2')->getDataType());
    }

    public function test_service_ticket_export_uses_labels_and_respects_search(): void
    {
        $station = Station::query()->create(['station_number' => 4, 'name' => 'Station 4', 'address' => '6880 Indian Creek Drive', 'is_active' => true]);
        $apparatus = Apparatus::query()->create([
            'station_id' => $station->id, 'unit_id' => 'R4', 'name' => 'Rescue 4', 'type' => 'Rescue', 'vehicle_number' => '4004',
            'designation' => 'R4', 'slug' => 'rescue-4', 'make' => 'Freightliner', 'model' => 'M2', 'year' => 2020,
            'status' => 'In Service', 'current_engine_hours' => 200, 'current_miles' => 14000,
        ]);
        foreach ([['Pump primer inspection', 'urgent', 'submitted'], ['Prior tire service', 'routine', 'completed']] as $index => [$title, $priority, $status]) {
            ApparatusServiceTicket::query()->create([
                'client_submission_id' => fake()->uuid(), 'apparatus_id' => $apparatus->id, 'station_id' => $station->id,
                'unit_designation_snapshot' => 'R4', 'created_by_user_id' => $this->admin->id, 'requester_name_snapshot' => $this->admin->name,
                'origin' => 'fleet', 'category' => 'repair_mechanical', 'title' => $title, 'description' => '=1+1 formula-looking description',
                'priority' => $priority, 'status' => $status, 'completed_at' => $status === 'completed' ? now() : null,
            ]);
        }

        $component = Livewire::test(ListApparatusServiceTickets::class)->call('loadTable')
            ->set('activeTab', 'all')
            ->searchTable('primer')
            ->callTableAction('export', data: ['format' => 'xlsx', 'scope' => 'filtered', 'include_toggled_off' => true])
            ->assertHasNoTableActionErrors();
        $grid = $this->dataRows($this->workbook($component));

        self::assertCount(2, $grid, 'Header plus the one ticket that matches the search.');
        $headers = $grid[0];
        $row = array_combine($headers, $grid[1]);
        self::assertSame('Pump primer inspection', $row['Title']);
        self::assertSame('R4', $row['Unit']);
        self::assertSame('Repair / Mechanical', $row['Category']);
        self::assertSame('Submitted', $row['Status']);
        self::assertTrue(ApparatusServiceTicketResource::canExportTable());
    }

    public function test_export_action_adds_no_queries_when_checked_again_after_render(): void
    {
        $page = Livewire::test(ListInventoryLocations::class)->call('loadTable');
        InventoryLocationResource::canExportTable(); // warm role and permission caches the page render already loads

        DB::enableQueryLog();
        DB::flushQueryLog();
        InventoryLocationResource::canExportTable();
        InventoryLocationResource::canExportTable();
        $queries = DB::getQueryLog();
        DB::disableQueryLog();

        self::assertSame([], $queries);
        $page->assertTableActionVisible('export');
    }
