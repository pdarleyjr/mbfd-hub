    private function location(string $name, string $shelf, string $row, ?string $notes = null): InventoryLocation
    {
        return InventoryLocation::query()->create(['location_name' => $name, 'shelf' => $shelf, 'row' => $row, 'notes' => $notes]);
    }

    /** @return list<string> first-column values of the data sheet, header excluded */
    private function firstColumn(array $grid): array
    {
        return array_slice(array_column($grid, 0), 1);
    }

    public function test_inventory_location_export_honors_filters_search_and_all_scope(): void
    {
        $this->location('North Cage', 'A', '1');
        $this->location('South Cage', 'B', '2');
        $this->location('East Annex', 'B', '3');

        $filtered = Livewire::test(ListInventoryLocations::class)->call('loadTable')
            ->filterTable('shelf', 'B')
            ->searchTable('Cage')
            ->callTableAction('export', data: ['format' => 'xlsx', 'scope' => 'filtered'])
            ->assertHasNoTableActionErrors()
            ->assertFileDownloaded('MBFD - Inventory Locations - '.CarbonImmutable::now('America/New_York')->format('Y-m-d').'.xlsx');
        $book = $this->workbook($filtered);
        self::assertSame(['South Cage - Shelf B - Row 2'], $this->firstColumn($this->dataRows($book)));

        $about = [];
        foreach ($book->getSheetByName('About this export')->toArray() as [$label, $value]) {
            $about[$label] = $value;
        }
        self::assertSame('1', $about['Row count']);
        self::assertStringContainsString('Cage', $about['Filters and search']);
        self::assertStringContainsString('B', $about['Filters and search']);
        self::assertSame($this->admin->name, $about['Generated by']);

        $all = Livewire::test(ListInventoryLocations::class)->call('loadTable')
            ->filterTable('shelf', 'B')
            ->searchTable('Cage')
            ->callTableAction('export', data: ['format' => 'xlsx', 'scope' => 'all'])
            ->assertHasNoTableActionErrors();
        $book = $this->workbook($all);
        self::assertEqualsCanonicalizing(
            ['North Cage - Shelf A - Row 1', 'South Cage - Shelf B - Row 2', 'East Annex - Shelf B - Row 3'],
            $this->firstColumn($this->dataRows($book)),
        );
        $about = [];
        foreach ($book->getSheetByName('About this export')->toArray() as [$label, $value]) {
            $about[$label] = $value;
        }
        self::assertSame('3', $about['Row count']);
        self::assertSame('None', $about['Filters and search']);
        self::assertStringContainsString('All records', $about['Scope']);
    }

    public function test_export_follows_visible_columns_and_can_include_columns_turned_off(): void
    {
        $this->location('North Cage', 'A', '1', 'Forklift access only');

        $default = $this->workbook(Livewire::test(ListInventoryLocations::class)->call('loadTable')
            ->callTableAction('export', data: ['format' => 'xlsx', 'scope' => 'filtered']));
        self::assertSame(['Location', 'Items', 'Updated at'], $this->dataRows($default)[0]);

        $withHidden = $this->workbook(Livewire::test(ListInventoryLocations::class)->call('loadTable')
            ->callTableAction('export', data: ['format' => 'xlsx', 'scope' => 'filtered', 'include_toggled_off' => true]));
        $grid = $this->dataRows($withHidden);
        self::assertSame(['Location', 'Items', 'Notes', 'Updated at'], $grid[0]);
        self::assertSame('Forklift access only', $grid[1][2]);
    }

    public function test_export_selected_is_limited_to_selected_records_and_ignores_unknown_ids(): void
    {
        $one = $this->location('North Cage', 'A', '1');
        $two = $this->location('South Cage', 'B', '2');
        $this->location('East Annex', 'B', '3');

        $component = Livewire::test(ListInventoryLocations::class)->call('loadTable')
            ->callTableBulkAction('export_selected', [$one->getKey(), $two->getKey(), 999999], data: ['format' => 'xlsx'])
            ->assertHasNoTableBulkActionErrors();

        $book = $this->workbook($component);
        self::assertEqualsCanonicalizing(
            ['North Cage - Shelf A - Row 1', 'South Cage - Shelf B - Row 2'],
            $this->firstColumn($this->dataRows($book)),
        );
    }

    public function test_selected_scope_is_intersected_with_the_authorized_table_query(): void
    {
        $visible = $this->location('North Cage', 'A', '1');
        $restricted = $this->location('Restricted Cage', 'Z', '9');

        $page = Livewire::test(ListInventoryLocations::class)->call('loadTable');
        $table = $page->instance()->getTable();
        // The resource query may exclude rows the viewer is not allowed to see; model that restriction.
        $table->modifyQueryUsing(fn ($query) => $query->where('shelf', '!=', 'Z'));

        $dataset = app(\App\Services\Exports\TableExportService::class)->buildDataset(
            $this->admin, $page->instance(), InventoryLocationResource::class, 'xlsx', 'selected', false,
            [$visible->getKey(), $restricted->getKey()],
        );

        self::assertSame(1, $dataset->rowCount());
        self::assertSame('North Cage - Shelf A - Row 1', $dataset->rows[0][0]->display());
    }

