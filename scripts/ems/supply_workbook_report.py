def esc(value: Any) -> str:
    return "" if value is None else str(value).replace("|", "/").replace("\n", " ")


def table(headers: list[str], rows: list[list[Any]]) -> list[str]:
    if not rows:
        return ["_None._", ""]
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(esc(c) for c in row) + " |" for row in rows]
    return out + [""]


def write_report(result: dict, changes: list[dict], path: Path) -> None:
    src, exc, items = result["source"], result["exceptions"], result["items"]
    counts = src["row_counts"]
    lines = [
        "# Supply room workbook import: what was found",
        "",
        "Generated by `scripts/ems/extract_supply_workbook.py`. Do not edit by hand; run the script again.",
        "",
        f"Source: `{src['file_name']}` (sha256 `{src['sha256']}`). Only the sheets **Supply Room Count** (starting counts) and **Supply Room Inventory** "
        "(shelves, order levels, package sizes) are read. The vendor lists and the old audit sheet are not inputs.",
        "",
        "How to read this: `php artisan ems:apply-supply-workbook` is a dry run until `--apply` is added. Applying writes one starting-count snapshot and "
        "changes nothing that a person has edited since the list was first loaded. Every group below says what will happen to its rows.",
        "",
        "## Totals",
        "",
    ]
    lines += table(["What", "Number"], [
        ["Count sheet rows with an item name", counts["count_sheet_item_rows"]],
        ["  with a quantity (including zero)", counts["count_sheet_populated_rows"]],
        ["  with a blank quantity", counts["count_sheet_blank_quantity_rows"]],
        ["Count sheet quantities with no item name", counts["count_sheet_quantity_without_item"]],
        ["Inventory sheet item rows", counts["inventory_sheet_item_rows"]],
        ["Hub items found on the Count sheet", counts["hub_items_matched_on_count"]],
        ["Hub items found on the Inventory sheet", counts["hub_items_matched_on_inventory"]],
        ["New items to create", counts["new_items"]],
        ["Items that get a starting count", counts["baselines"]],
    ])
    lines += ["Rows per group:", ""]
    labels = {g: title for g, title, _ in GROUPS}
    lines += table(["Group", "Rows"], [[labels.get(g, g), n] for g, n in counts["exceptions_by_group"].items()])

    for group, title, what in GROUPS:
        rows = [e for e in exc if e["group"] == group]
        lines += [f"## {title} ({len(rows)})", "", what, ""]
        lines += table(["Sheet row", "Item", "Detail", "What happens"],
                       [[f"{e['sheet']} {e['row']}" if e["sheet"] else "", e["item_text"], e["detail"], e["action"]] for e in rows])

    lines += ["## Changes to existing items", "",
              "Compared with what the Hub holds today (loaded from the printed 2021 list). Nothing a person has edited is changed. "
              "Each change that is applied is written to the item's history as \"Workbook import 2026\".", ""]
    lines += table(["Item", "Field", "Hub today", "Workbook"], [[c["item_text"], c["field"], c["before"], c["after"]] for c in changes])

    no_count = [i for i in items if not i["new"] and i["count"] is None and not any(i["source_row_key"] == e["source_row_key"] for e in exc if e["group"] == "blank_quantity")]
    lines += [f"## Items with no row on the Count sheet ({len(no_count)})", "",
              "These Hub items have no line on the Count sheet at all. They stay not counted (never zero) until Monday's count.", ""]
    lines += table(["Item", "Shelf"], [[i["item_text"], i["shelf"]["code"] or "(none)"] for i in no_count])
    path.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8", newline="\n")
