<?php

declare(strict_types=1);

namespace App\Services\Exports;

use PhpOffice\PhpSpreadsheet\Cell\DataType;
use PhpOffice\PhpSpreadsheet\Spreadsheet;
use PhpOffice\PhpSpreadsheet\Style\Alignment;
use PhpOffice\PhpSpreadsheet\Style\Fill;
use PhpOffice\PhpSpreadsheet\Worksheet\Worksheet;
use PhpOffice\PhpSpreadsheet\Writer\Xlsx;

/** Builds an .xlsx with typed cells, frozen header, autofilter and an "About this export" sheet. */
final class XlsxExportWriter
{
    private const DATE_FORMAT = 'yyyy-mm-dd';

    private const DATETIME_FORMAT = 'yyyy-mm-dd hh:mm';

    private const WIDTH_SAMPLE_ROWS = 200;

    public function write(ExportDataset $dataset): string
    {
        $book = new Spreadsheet;
        $book->getProperties()
            ->setCreator('MBFD Hub')
            ->setTitle(CellSanitizer::cell($dataset->title));

        $sheet = $book->getActiveSheet();
        $sheet->setTitle($this->sheetTitle($dataset->title));
        $this->writeData($sheet, $dataset);
        $this->writeAbout($book->createSheet(), $dataset);
        $book->setActiveSheetIndex(0);

        $stream = fopen('php://temp', 'w+');
        (new Xlsx($book))->save($stream);
        rewind($stream);
        $bytes = (string) stream_get_contents($stream);
        fclose($stream);
        $book->disconnectWorksheets();

        return $bytes;
    }

    private function writeData(Worksheet $sheet, ExportDataset $dataset): void
    {
        $columns = max(1, $dataset->columnCount());

        foreach ($dataset->headers as $index => $header) {
            $this->putText($sheet, $index + 1, 1, $header);
        }

        foreach ($dataset->rows as $rowIndex => $row) {
            foreach ($row as $index => $cell) {
                $this->putCell($sheet, $index + 1, $rowIndex + 2, $cell);
            }
        }

        $lastColumn = $sheet->getHighestColumn();
        $lastRow = max(1, $dataset->rowCount() + 1);
        $range = 'A1:'.$lastColumn.$lastRow;

        $header = $sheet->getStyle('A1:'.$lastColumn.'1');
        $header->getFont()->setBold(true);
        $header->getFill()->setFillType(Fill::FILL_SOLID)->getStartColor()->setRGB('E6ECF3');
        $header->getAlignment()->setVertical(Alignment::VERTICAL_CENTER)->setWrapText(true);

        $sheet->getStyle($range)->getAlignment()->setVertical(Alignment::VERTICAL_TOP);
        if ($dataset->rowCount() > 0) {
            $sheet->getStyle('A2:'.$lastColumn.$lastRow)->getAlignment()->setWrapText(true);
        }

        $sheet->freezePane('A2');
        $sheet->setAutoFilter($range);

        foreach (range(1, $columns) as $index) {
            $sheet->getColumnDimensionByColumn($index)->setWidth($this->columnWidth($dataset, $index - 1));
        }
    }

    private function putCell(Worksheet $sheet, int $column, int $row, ExportCell $cell): void
    {
        switch ($cell->kind) {
            case ExportCell::NUMBER:
                $sheet->setCellValueExplicit([$column, $row], $cell->value, DataType::TYPE_NUMERIC);
                break;
            case ExportCell::DATE:
            case ExportCell::DATETIME:
                $sheet->setCellValueExplicit([$column, $row], (float) $cell->value, DataType::TYPE_NUMERIC);
                $sheet->getStyle([$column, $row])->getNumberFormat()->setFormatCode(
                    $cell->kind === ExportCell::DATE ? self::DATE_FORMAT : self::DATETIME_FORMAT
                );
                break;
            default:
                if ($cell->value !== '') {
                    $this->putText($sheet, $column, $row, (string) $cell->value);
                }
        }
    }

    private function putText(Worksheet $sheet, int $column, int $row, string $text): void
    {
        $sheet->setCellValueExplicit([$column, $row], CellSanitizer::cell($text), DataType::TYPE_STRING);
    }

    private function columnWidth(ExportDataset $dataset, int $index): float
    {
        $longest = mb_strlen($dataset->headers[$index] ?? '');
        foreach (array_slice($dataset->rows, 0, self::WIDTH_SAMPLE_ROWS) as $row) {
            if (isset($row[$index])) {
                $longest = max($longest, min(60, mb_strlen($row[$index]->display())));
            }
        }

        return (float) min(60, max(10, $longest + 2));
    }

    private function writeAbout(Worksheet $about, ExportDataset $dataset): void
    {
        $about->setTitle('About this export');
        $lines = [
            ['Title', $dataset->title],
            ['Generated', $dataset->generatedAt->format('M j, Y g:i A T')],
            ['Generated by', $dataset->generatedBy],
            ['Scope', $dataset->scopeLabel],
            ['Filters and search', $dataset->filterSummary === [] ? 'None' : implode('; ', $dataset->filterSummary)],
            ['Sort', $dataset->sortSummary ?? 'Table default'],
            ['Row count', (string) $dataset->rowCount()],
            ['Time zone', 'Dates and times are America/New_York'],
            ['Source', 'MBFD Hub admin table. Values match what the table shows.'],
        ];

        foreach ($lines as $index => [$label, $value]) {
            $this->putText($about, 1, $index + 1, $label);
            $this->putText($about, 2, $index + 1, $value);
        }

        $about->getStyle('A1:A'.count($lines))->getFont()->setBold(true);
        $about->getStyle('B1:B'.count($lines))->getAlignment()->setWrapText(true)->setVertical(Alignment::VERTICAL_TOP);
        $about->getColumnDimension('A')->setWidth(22);
        $about->getColumnDimension('B')->setWidth(80);
    }

    private function sheetTitle(string $title): string
    {
        $clean = trim((string) preg_replace('/\s+/', ' ', (string) preg_replace('/[\\\\\/\?\*\[\]:]+/', ' ', $title)));
        $clean = trim(mb_substr($clean, 0, 31));

        return $clean === '' || strcasecmp($clean, 'About this export') === 0 ? 'Export' : $clean;
    }
}
